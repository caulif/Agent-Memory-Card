#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct MemoryGateDecision {
    pub disposition: MemoryGateDisposition,
    pub route: &'static str,
    pub flags: Vec<&'static str>,
    pub reason: &'static str,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum MemoryGateDisposition {
    Accept,
    ReviewOnly,
    Reject,
}

pub(crate) fn evaluate_memory_candidate(
    title: &str,
    body: &str,
    evidence: &str,
    kind: &str,
    scope: &str,
) -> MemoryGateDecision {
    let combined = format!("{title}\n{body}\n{evidence}\n{kind}\n{scope}");
    let lower = combined.to_lowercase();
    let durable = has_durable_marker(&lower);

    if contains_secret(&lower) {
        return reject("secret", "Candidate contains secret-like content.");
    }
    if looks_like_generated_or_internal_artifact(&lower) {
        return reject(
            "generated-or-internal-artifact",
            "Candidate is generated artifact or internal extraction metadata.",
        );
    }
    if looks_like_memory_pipeline_meta(&lower) {
        return reject(
            "memory-pipeline-meta",
            "Candidate describes the memory extraction pipeline, not durable user preference.",
        );
    }
    if looks_like_current_task_state(&lower) {
        return reject(
            "current-task-state",
            "Candidate describes current task state.",
        );
    }
    if looks_like_one_off_write_scope(&lower, durable) {
        return reject(
            "one-off-write-scope",
            "Candidate describes a one-off task write scope.",
        );
    }
    if looks_like_rebuildable_code_fact(&lower, durable) {
        return reject(
            "rebuildable-code-fact",
            "Candidate can be rediscovered from the current repository.",
        );
    }
    if looks_like_ephemeral_reference(&lower, durable) {
        return reject(
            "ephemeral-reference",
            "Candidate is likely to expire quickly.",
        );
    }
    if looks_like_reference_pointer(&lower) {
        return MemoryGateDecision {
            disposition: MemoryGateDisposition::ReviewOnly,
            route: "review_only",
            flags: vec!["reference-pointer"],
            reason: "Reference-like memories should be reviewed without default compilation.",
        };
    }
    MemoryGateDecision {
        disposition: MemoryGateDisposition::Accept,
        route: "always_on_rule",
        flags: Vec::new(),
        reason: "Candidate passed memory gate.",
    }
}

fn reject(flag: &'static str, reason: &'static str) -> MemoryGateDecision {
    MemoryGateDecision {
        disposition: MemoryGateDisposition::Reject,
        route: "review_only",
        flags: vec![flag],
        reason,
    }
}

