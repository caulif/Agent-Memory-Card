#[cfg(test)]
mod tests {
    use super::*;

    fn decision(text: &str) -> MemoryGateDecision {
        evaluate_memory_candidate(text, text, text, "constraint", "project")
    }

    #[test]
    fn rejects_one_off_scope_without_durable_marker() {
        assert_eq!(
            decision("只修改 app/src/main.tsx，不要改 Rust。").disposition,
            MemoryGateDisposition::Reject
        );
        assert_eq!(
            decision("不要改 Rust。").disposition,
            MemoryGateDisposition::Reject
        );
    }

    #[test]
    fn keeps_durable_project_rule() {
        assert_eq!(
            decision("以后所有 Rust 项目提交前运行 cargo test。").disposition,
            MemoryGateDisposition::Accept
        );
    }

    #[test]
    fn rejects_memory_pipeline_meta_rules() {
        assert_eq!(
            decision("当生成、筛选或展示候选记忆时，只保留高置信度且可执行的少量候选。")
                .disposition,
            MemoryGateDisposition::Reject
        );
        assert_eq!(
            decision("当规划或评估开发工作时，先确保核心功能链路和用户体验稳定；再考虑周边功能。")
                .disposition,
            MemoryGateDisposition::Reject
        );
        assert_eq!(
            decision("修改卡片改写器时，必须抽样审阅最终卡片，不要只看质量分。").disposition,
            MemoryGateDisposition::Reject
        );
    }

    #[test]
    fn keeps_supported_failure_flow_workflow() {
        let decision = evaluate_memory_candidate(
            "提取异常先定位链路断点",
            "当记忆提取结果异常少、质量差或没有进入最终卡片阶段时，先定位链路断点，包括候选召回、LLM induction、JSON 解析、质量门控和 crystallize。",
            "FailureFlowSummary:\n- signal:pipeline_break obs:a text:LLM induction JSON 被截断，解析失败，所以没有进入最终 crystallize 卡片阶段。",
            "procedure",
            "global",
        );

        assert_eq!(decision.disposition, MemoryGateDisposition::Accept);
    }
}
